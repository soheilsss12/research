def source_rows(sources):
    return "\n".join(f"| {i} | {grade} | {origin} | {claim} | {url} |" for i, grade, origin, claim, url in sources)


def localize_terms(body):
    """Keep explanatory prose professionally Persian; retain product/technical acronyms."""
    replacements = [
        ("desk research", "پژوهش اسنادی"),
        ("scope", "دامنه"),
        ("outcome", "نتیجه"),
        ("survey", "پیمایش"),
        ("commitment", "تعهد"),
        ("category", "دسته"),
        ("substitute", "جایگزین"),
        ("adoption", "پذیرش"),
        ("failure mode", "نقطه شکست"),
        ("baseline", "خط پایه"),
        ("pilot", "آزمایش محدود"),
        ("workflow", "جریان کار"),
        ("audit", "ممیزی"),
        ("reversal", "تغییر صریح دامنه"),
        ("control-plane", "لایه کنترل"),
        ("service/network-heavy", "عملیاتی/شبکه‌محور"),
        ("enterprise", "سازمانی"),
        ("claim فروشنده", "ادعای فروشنده"),
        ("claim شرکت", "ادعای شرکت"),
    ]
    for foreign, persian in replacements:
        body = body.replace(foreign, persian)
    return body

